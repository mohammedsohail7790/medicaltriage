/**
 * The component and licence register (M-016): every third-party component that ships, with its licence, from the software bill of
 * materials, plus the components that are not npm packages. Licences are sorted into those that can be used and shipped freely
 * (permissive), those with conditions that need a decision (weak copyleft) and those that must not be used (strong copyleft, unknown).
 */

type Component = { name: string; version: string; licenses?: Array<{ expression?: string }> };
export type Bom = { components: Component[]; metadata?: { timestamp?: string } };

const PERMISSIVE = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|Unlicense|CC0-1\.0|BlueOak-1\.0\.0|MIT-0|Zlib|\(MIT AND Zlib\))$/;
const FONT_LICENCE = /^OFL-1\.1$/;
const WEAK_COPYLEFT = /(MPL|LGPL|EPL|CDDL)/;
const STRONG_COPYLEFT = /(^|[^L])GPL|AGPL|SSPL/;

export type Category = "permissive" | "font-licence" | "weak-copyleft" | "strong-copyleft" | "unknown";
export function categorise(licence: string | undefined): Category {
  if (!licence) return "unknown";
  if (PERMISSIVE.test(licence)) return "permissive";
  if (FONT_LICENCE.test(licence)) return "font-licence";
  if (STRONG_COPYLEFT.test(licence)) return "strong-copyleft";
  if (WEAK_COPYLEFT.test(licence)) return "weak-copyleft";
  return "unknown";
}

const OTHER_COMPONENTS: Array<[string, string, string, string]> = [
  ["Node.js", "24 (container base image node:24-bookworm-slim)", "MIT and the licences of its bundled components", "Runtime"],
  ["Debian GNU/Linux (base image)", "bookworm", "Mixed free-software licences, including GPL for system tools", "Operating-system layer of the container; not linked into the application"],
  ["PostgreSQL", "16", "PostgreSQL Licence (permissive)", "Database; used as a service, not distributed"],
  ["Noto Sans Arabic", "via @fontsource/noto-sans-arabic", "SIL Open Font Licence 1.1", "Embedded in referral letters; the licence allows embedding in documents"],
  ["Noto Naskh Arabic", "via @fontsource/noto-naskh-arabic", "SIL Open Font Licence 1.1", "Installed; not used in the final letters"],
  ["Inter, Noto Sans Arabic (web)", "Google Fonts", "SIL Open Font Licence 1.1", "Loaded by the browser from Google's font hosts"],
  ["Python scripts", "3.x, standard library only for the simulation tools", "PSF Licence", "Developer tooling in python/, not shipped in the container"],
  ["STCC clinical protocol content", "licensed release", "Commercial licence (not open source)", "Licensed to IRISSTAR; named-user coverage to be confirmed (F-001, M-016); not in the repository"],
  ["Open-source clinical decision rules", "see docs/open-source-clinical-decision-rules-content.md", "As stated per source", "Content, reviewed per source"]
];

export function renderLicenceRegister(bom: Bom): string {
  const rows = bom.components.map((c) => ({ name: c.name, version: c.version, licence: c.licenses?.[0]?.expression }));
  const counts: Record<Category, number> = { permissive: 0, "font-licence": 0, "weak-copyleft": 0, "strong-copyleft": 0, unknown: 0 };
  for (const r of rows) counts[categorise(r.licence)] += 1;
  const byLicence = new Map<string, number>();
  for (const r of rows) byLicence.set(r.licence ?? "(none)", (byLicence.get(r.licence ?? "(none)") ?? 0) + 1);
  const summary = [...byLicence.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${categorise(l === "(none)" ? undefined : l)} | ${n} |`);
  const needDecision = rows.filter((r) => ["weak-copyleft", "strong-copyleft", "unknown", "font-licence"].includes(categorise(r.licence)));
  return `# Component and licence register

Generated by \`pnpm evidence:generate\` from the software bill of materials (\`docs/sbom/sbom.cdx.json\`, ${bom.components.length} production components). Review it at every release; the continuous-integration licence check allows only the licences listed here.

## Summary

| Licence | Category | Components |
|---|---|---|
${summary.join("\n")}

- **Permissive:** ${counts.permissive}. May be used and shipped; the notices are kept with the components.
- **Font licence (SIL OFL 1.1):** ${counts["font-licence"]}. Permissive for use and embedding; the fonts may not be sold on their own.
- **Weak copyleft:** ${counts["weak-copyleft"]}. Conditions apply to changes to the component itself; none needs a decision unless it is modified.
- **Strong copyleft:** ${counts["strong-copyleft"]}. Not permitted in what ships.
- **Unknown or missing:** ${counts.unknown}. Must be resolved before release.

${needDecision.length === 0 ? "No component needs a decision." : `## Components that need a decision or a note\n\n| Component | Version | Licence | Category |\n|---|---|---|---|\n${needDecision.map((r) => `| ${r.name} | ${r.version} | ${r.licence ?? "(none)"} | ${categorise(r.licence)} |`).join("\n")}\n`}
## Components that are not npm packages

| Component | Version | Licence | Use |
|---|---|---|---|
${OTHER_COMPONENTS.map((o) => `| ${o.join(" | ")} |`).join("\n")}

## Every production component

| Component | Version | Licence |
|---|---|---|
${rows.sort((a, b) => a.name.localeCompare(b.name)).map((r) => `| ${r.name} | ${r.version} | ${r.licence ?? "(none)"} |`).join("\n")}

Development-only tools (test runners, build tools, type checkers) are not shipped and are not listed; the same licence check covers them in the pipeline.
`;
}
