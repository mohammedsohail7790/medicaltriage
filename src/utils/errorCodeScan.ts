import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";

/** Finds the machine-readable error codes the application can return (NFR-114), by reading its source. */

export type FoundCode = { code: string; files: string[]; status?: number };

function sources(dir: string): string[] {
  return readdirSync(dir).flatMap((entry) => {
    const full = path.join(dir, entry);
    return statSync(full).isDirectory() ? (entry === "scripts" ? [] : sources(full)) : full.endsWith(".ts") ? [full] : [];
  });
}

const PATTERNS: RegExp[] = [
  /new \w*Error\(\s*(\d{3})\s*,\s*(?:"[^"]*"|`[^`]*`)\s*,\s*"([A-Z][A-Z0-9_]{5,})"/g, // new XError(status, message, "CODE")
  /new \w*Error\(\s*(?:"[^"]*"|`[^`]*`)\s*,\s*"([A-Z][A-Z0-9_]{5,})"/g, // new XError(message, "CODE")
  /\bcode:\s*"([A-Z][A-Z0-9_]{5,})"/g // { code: "CODE" }
];

export function scanErrorCodes(srcDir = path.resolve(process.cwd(), "src")): FoundCode[] {
  const found = new Map<string, FoundCode>();
  for (const file of sources(srcDir)) {
    const text = readFileSync(file, "utf8");
    const rel = path.relative(process.cwd(), file);
    PATTERNS.forEach((pattern, index) => {
      for (const match of text.matchAll(pattern)) {
        const code = index === 0 ? match[2] : match[1];
        const status = index === 0 ? Number(match[1]) : undefined;
        const entry = found.get(code) ?? { code, files: [] };
        if (!entry.files.includes(rel)) entry.files.push(rel);
        if (status && !entry.status) entry.status = status;
        found.set(code, entry);
      }
    });
  }
  return [...found.values()].sort((a, b) => a.code.localeCompare(b.code));
}

const STEPS: Array<[RegExp, string]> = [
  [/^QUEUE_|^QA_/, "Find the case id in the request and look it up in the queue board. Check who holds the lock and the stage, then read the case's transition log for the last change."],
  [/^SESSION_|^AUTH|^MFA|^LOGIN|^OAUTH|^CAPTCHA/, "Check the sign-in events for the user in the audit trail (FAILED_LOGIN, MFA, CAPTCHA). Confirm the clock on the client and that the account is active."],
  [/^RULE_|^SCHEDULE_|^RUN_|^BRANCH_|^TEMPLATE_|^INCIDENT_|^HANDOFF_|^REFERRAL_|^TELECONSULT_/, "Read the item named in the request under the admin Operations or Clinical views, check its status against the message, and repeat the action if the state has moved on."],
  [/^EXPORT_|^RETENTION_|^ARCHIVE_|^INTEGRITY_/, "Open the export, retention or integrity view and read the latest result and its audit event. Nothing is lost on these errors; the action did not complete."],
  [/^INTEGRATION_|^WEBHOOK_|^BROKER_|^JOB_/, "Open Admin, Integrations: look at the delivery or job, its attempts and last error, then the interface log for the same correlation id."]
];

export function diagnosisFor(code: string): string {
  return STEPS.find(([pattern]) => pattern.test(code))?.[1] ?? "Search the audit trail and the request log for the request id returned with the error (X-Request-Id), then follow the trace for that request.";
}

export function renderCatalogue(codes: FoundCode[]): string {
  const rows = codes.map((c) => `| \`${c.code}\` | ${c.status ?? "see handler"} | ${c.files.map((f) => `\`${f}\``).join(", ")} | ${diagnosisFor(c.code)} |`);
  return `# Error codes and manual diagnosis

Generated by \`pnpm errors:catalogue\` from the source. Every error response carries a request id (\`X-Request-Id\`) and a trace id (\`traceparent\`); quote both when raising a problem. Version 2 of the API returns RFC 7807 problem documents, version 1 returns \`{ "error": "..." }\`; the code, where there is one, is in \`code\`.

## First steps for any error

1. Note the request id and the trace id from the response headers.
2. In Admin, Operations, open the trace for that id: it shows the request, each database call and each external call, with timings and failures.
3. In the audit trail, search for the same user and time; security and administrative actions are recorded with before and after values.
4. If an external system is involved, open Admin, Integrations and read the interface log entry with the same correlation id.

## Codes

| Code | HTTP | Raised in | What to check |
|---|---|---|---|
${rows.join("\n")}
`;
}
