// Sprint 10: builds the reply verification register that goes to the tester. One row for every reply submitted to
// Qatar Airways, with the files it names (checked to exist) and empty columns for the tester's result.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export type ReplyRow = { id: string; position: string; evidence: string; todo: string };

export function evidenceFiles(evidence: string): string[] {
  return [...new Set(evidence.match(/[\w@./-]+\/[\w@./-]+\.[A-Za-z0-9]{1,5}\b/g) ?? [])];
}

const csvCell = (v: string) => `"${v.replace(/"/g, '""').replace(/\s+/g, " ").trim()}"`;

export function renderRegister(rows: ReplyRow[], exists: (p: string) => boolean): { md: string; csv: string } {
  const namedMissing: string[] = [];
  let withFiles = 0;
  const lines: string[] = [];
  const csv = ["Ref,Submitted position,What the reply relies on,Files named,Files present,Result (pass / fail / difference),Tester,Notes"];
  for (const r of rows) {
    const files = evidenceFiles(r.evidence);
    const missing = files.filter((f) => !exists(f));
    if (files.length) withFiles++;
    for (const m of missing) namedMissing.push(`${r.id}: ${m}`);
    lines.push(`| ${r.id} | ${r.position} | ${files.length ? files.map((f) => `\`${f}\``).join(", ") : "none named"} | ${files.length ? (missing.length ? `**missing: ${missing.join(", ")}**` : "all present") : "-"} |`);
    csv.push([r.id, r.position, r.evidence, files.join("; "), files.length ? (missing.length ? "NO" : "yes") : "n/a", "", "", ""].map(csvCell).join(","));
  }
  const md = `# Reply verification register

Every reply submitted to Qatar Airways is the contract. This register lists all ${rows.length} of them so each can be checked against the delivered behaviour. It is generated by \`pnpm validation:pack\` from \`docs/validation/reply-register.json\`.

What this file proves, and what it does not: for ${withFiles} rows the reply names files as evidence, and the check below confirms each named file exists${namedMissing.length ? ` (**${namedMissing.length} do not**)` : " (all do)"}. It does **not** prove that a reply is true. The other ${rows.length - withFiles} rows name no file, and every row still needs a person to try the behaviour. The tester records the result for each row in \`reply-verification-register.csv\`.

| Ref | Submitted position | Files named | Check |
|---|---|---|---|
${lines.join("\n")}
`;
  return { md, csv: csv.join("\n") + "\n" };
}

if (process.argv[1]?.endsWith("generateValidationPack.ts")) {
  const root = process.cwd();
  const rows = JSON.parse(readFileSync(path.join(root, "docs/validation/reply-register.json"), "utf8")) as ReplyRow[];
  const { md, csv } = renderRegister(rows, (p) => existsSync(path.join(root, p)));
  writeFileSync(path.join(root, "docs/validation/reply-verification-register.md"), md);
  writeFileSync(path.join(root, "docs/validation/reply-verification-register.csv"), csv);
  console.log(`Wrote the reply verification register: ${rows.length} rows.`);
}
